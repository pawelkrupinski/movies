#!/usr/bin/env python3
"""Generate the tab-separated tables under geodata/src/main/resources/generated/pl-pages/
(read by `models.PolishPages`) from data/pl/pages.json.

The Scala side of `build_pages.py`: every Polish venue's page, as data. The 41
major cities stay hand-declared `case object`s (their labels are hand-declined)
and read their venue lists from `major-cinemas.tsv`; every other page is a row of
`pages.tsv` (+ its venues in `cinemas.tsv`) that `City` turns into a `PolishPage`.
A venue is named by its Scala object name (`KinoIskra`), which `PolishPages` resolves
at load and fails on when the object is gone.

    python3 data/pl/scripts/generate_polish_pages.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PAGES = ROOT / "data/pl/pages.json"
OUT_DIR = ROOT / "geodata/src/main/resources/generated/pl-pages"
sys.path.insert(0, str(ROOT / "data" / "scripts"))
from generated_tables import list_cell, write_table  # noqa: E402
# The apps' first-run city lists (before the live catalogue arrives) carry the
# same pages; their Polish block sits between these markers.
MOBILE = [
    (ROOT / "android/app/src/main/java/pl/kinowo/model/City.kt",
     lambda p: f'        City("{p["slug"]}", "{p["label"]}", {p["lat"]:.4f}, {p["lon"]:.4f}, "pl", "{p["voivodeship"]}"),'),
    (ROOT / "ios/Kinowo/Models/City.swift",
     lambda p: f'        City(slug: "{p["slug"]}", name: "{p["label"]}", lat: {p["lat"]:.4f}, lon: {p["lon"]:.4f}, '
               f'country: "pl", region: "{p["voivodeship"]}"),'),
]
MOBILE_START = "        // ── Poland: GENERATED by data/pl/scripts/generate_polish_pages.py — do not edit by hand.\n"
MOBILE_END = "        // ── end Poland (generated)\n"


def main():
    data = json.loads(PAGES.read_text(encoding="utf-8"))
    pages, retired = data["pages"], data["retired"]
    majors = [p for p in pages if p["kind"] == "major"]
    others = [p for p in pages if p["kind"] != "major"]

    write_table(OUT_DIR / "pages.tsv", [
        [p["slug"], p["name"], p["locative"], repr(p["lat"]), repr(p["lon"]), p["voivodeship"],
         "true" if p["kind"] == "cluster" else "false"] for p in others])
    write_table(OUT_DIR / "cinemas.tsv", [[p["slug"], list_cell(p["cinemas"])] for p in others])
    write_table(OUT_DIR / "major-cinemas.tsv",
                [[p["slug"], p["voivodeship"], list_cell(p["cinemas"])] for p in majors])
    write_table(OUT_DIR / "retired.tsv", [[k, v] for k, v in sorted(retired.items())])

    for p in pages:
        p["label"] = f"{p['name']} i okolice" if p["kind"] == "cluster" else p["name"]
    for path, line in MOBILE:
        text = path.read_text(encoding="utf-8")
        head, rest = text.split(MOBILE_START, 1)
        _, tail = rest.split(MOBILE_END, 1)
        path.write_text(head + MOBILE_START + "".join(line(p) + "\n" for p in pages) + MOBILE_END + tail,
                        encoding="utf-8")
    print(f"Wrote {OUT_DIR.relative_to(ROOT)}: {len(majors)} major cities, {len(others)} generated pages, "
          f"{len(retired)} retired slugs")


if __name__ == "__main__":
    main()
