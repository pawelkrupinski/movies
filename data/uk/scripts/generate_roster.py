#!/usr/bin/env python3
"""Generate common/src/main/scala/models/UkPages.scala from data/uk/pages.json.

The Scala side of `build_pages.py`: every UK venue's page, as code. The venues
stay the hand-written `case object`s in Cinema.scala; this says which page lists
each. London is hand-declared in `City` (it keeps its compass areas) and reads
its venues from `UkPages.london`; every other page is a generated row that
`City` turns into a `UkPage`. The apps' first-run city lists carry the same
pages, between the UK markers below.

    python3 data/uk/scripts/generate_roster.py
"""
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PAGES = ROOT / "data/uk/pages.json"
TOWNS = ROOT / "data/uk/towns.json"
OUT = ROOT / "common/src/main/scala/models/UkPages.scala"
# The order the pickers show the nations in — the old roster's, kept in one place.
NATIONS = ["England", "Scotland", "Northern Ireland", "Wales", "Crown Dependencies"]


def mobile_row_kt(p):
    sub = f', "{p["subregion"]}"' if p["subregion"] else ""
    return f'        City("{p["slug"]}", "{p["label"]}", {p["lat"]:.4f}, {p["lon"]:.4f}, "uk", "{p["nation"]}"{sub}),'


def mobile_row_swift(p):
    sub = f', subregion: "{p["subregion"]}"' if p["subregion"] else ""
    return (f'        City(slug: "{p["slug"]}", name: "{p["label"]}", lat: {p["lat"]:.4f}, lon: {p["lon"]:.4f}, '
            f'country: "uk", region: "{p["nation"]}"{sub}),')


MOBILE = [(ROOT / "android/app/src/main/java/pl/kinowo/model/City.kt", mobile_row_kt),
          (ROOT / "ios/Kinowo/Models/City.swift", mobile_row_swift)]
MOBILE_START = "        // ── United Kingdom: GENERATED by data/uk/scripts/generate_roster.py — do not edit by hand.\n"
MOBILE_END = "        // ── end United Kingdom (generated)\n"
CHUNK = 40


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def seq(items):
    return "Seq(" + ", ".join(items) + ")"


def label(p):
    """The name a page shows — the Scala side's `UkPage.labels`, for the apps."""
    return f"{p['name']} area" if p["kind"] == "cluster" else p["name"]


def row(p, town_names):
    return (f"Row({q(p['slug'])}, {q(p['name'])}, {p['lat']}, {p['lon']}, {q(p['nation'])}, {q(p['county'])}, "
            f"multiTown = {'true' if p['kind'] == 'cluster' else 'false'}, "
            f"{seq(q(town_names[t]) for t in p['towns'])}, {seq(p['cinemas'])})")


def main():
    data = json.loads(PAGES.read_text(encoding="utf-8"))
    town_names = {k: t["name"] for k, t in json.loads(TOWNS.read_text(encoding="utf-8"))["towns"].items()}
    pages, retired = data["pages"], data["retired"]
    unknown = sorted({p["nation"] for p in pages} - set(NATIONS))
    if unknown:
        sys.exit(f"nations with no place in the picker's order: {unknown}")
    london = next(p for p in pages if p["slug"] == "london")
    others = [p for p in pages if p is not london]
    rows = [f"    {row(p, town_names)}" for p in others]
    chunks = [rows[i:i + CHUNK] for i in range(0, len(rows), CHUNK)]

    out = [
        "// GENERATED from data/uk/pages.json by data/uk/scripts/generate_roster.py",
        "// — do NOT edit by hand. Re-cluster with data/uk/scripts/build_pages.py.",
        "package models",
        "",
        "/** Which UK listing page every venue is on.",
        " *",
        " *  A major city (a place of 100,000+) lists only the venues inside it; every",
        " *  other venue is on a page of its own town (3+ venues) or of a cluster of small",
        " *  towns within a short drive, named after its biggest — never more than 40 km",
        " *  from it (see `data/uk/scripts/build_pages.py`). London is hand-declared in",
        " *  `City` for its compass areas and reads [[london]]; every other page is a",
        " *  [[Row]] that `City.ukPages` builds. */",
        "private[models] object UkPages {",
        "",
        "  /** A page. `multiTown` pages are named \"X area\"; `towns` is the town the page",
        "   *  is named after, then the rest of its towns. */",
        "  final case class Row(slug: String, name: String, lat: Double, lon: Double, nation: String, county: String,",
        "                       multiTown: Boolean, towns: Seq[String], cinemas: Seq[Cinema]) {",
        "    /** The page's name: the town, or \"<town> area\" for a cluster of towns. */",
        "    def nominative: String = if (multiTown) s\"$name area\" else name",
        "  }",
        "",
        f"  /** The nations in the order every picker shows them. */",
        f"  val nations: Seq[String] = {seq(q(n) for n in NATIONS)}",
        "",
        f"  val london: Row = {row(london, town_names)}",
        "",
    ]
    for i, c in enumerate(chunks):
        out.append(f"  private def chunk{i}: Seq[Row] = Seq(")
        out.extend(r + "," for r in c)
        out.append("  )")
        out.append("")
    out.append("  val rows: Seq[Row] = " + " ++ ".join(f"chunk{i}" for i in range(len(chunks))))
    out.append("")
    out.append("  /** Pages that no longer exist → the page holding the town each was named")
    out.append("   *  after, or — where none was — the page now holding most of its venues. */")
    out.append("  val retired: Map[String, String] = Map(")
    out.extend(f"    {q(k)} -> {q(v['page'])}," for k, v in sorted(retired.items()))
    out.append("  )")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")

    # The apps' fallback lists: a county holding more than one page is the
    # third picker step (`subregion`), as `/api/catalog` sends it.
    per_county = collections.Counter((p["nation"], p["county"]) for p in pages)
    mobile = list(pages)   # pages.json order: the majors biggest first, London leading
    for p in mobile:
        p["label"] = label(p)
        p["subregion"] = p["county"] if per_county[(p["nation"], p["county"])] > 1 else None
    for path, line in MOBILE:
        text = path.read_text(encoding="utf-8")
        head, rest = text.split(MOBILE_START, 1)
        _, tail = rest.split(MOBILE_END, 1)
        path.write_text(head + MOBILE_START + "".join(line(p) + "\n" for p in mobile) + MOBILE_END + tail,
                        encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: London and {len(others)} generated pages, {len(retired)} retired slugs")


if __name__ == "__main__":
    main()
