#!/usr/bin/env python3
"""Generate the UK roster's tables from data/uk: roster.json and pages.json.

Each is a tab-separated resource under geodata/src/main/resources/generated/
(`data/scripts/generated_tables.py`), read by a hand-written Scala adapter:

  * `uk-roster/venues.tsv` → `models.UkRoster` — every venue, from roster.json
    (`uk_roster.py` says what a row holds), keyed on the row's `object`, which
    code addresses a venue by (`UkRoster("ActOneActon")`) and which stays its
    `toString` as when it was a hand-written `case object`.
  * `uk-sources/sources.tsv` → `services.cinemas.uk.UkSourcesData` — each venue's
    primary feed and the Flicks slug it keeps as the aggregator fallback, in
    roster.json's order (the scrape order), for `UkScraperCatalog` and
    `ChainFlicksFallback`.
  * `uk-pages/*.tsv` → `models.UkPages` — the Scala side of `build_pages.py`:
    which page lists each venue (by key), the nations' order, the retired slugs.
    London is hand-declared in `City` (it keeps its compass areas) and reads its
    venues from `UkPages.london`; every other page is a row that `City` turns
    into a `UkPage`. The apps' first-run city lists carry the same pages,
    between the UK markers below.

    python3 data/uk/scripts/generate_roster.py
"""
import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "scripts"))
import uk_roster  # noqa: E402
from generated_tables import list_cell, option_cell, write_table  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
PAGES = ROOT / "data/uk/pages.json"
TOWNS = ROOT / "data/uk/towns.json"
GENERATED = ROOT / "geodata/src/main/resources/generated"
VENUES_OUT = GENERATED / "uk-roster/venues.tsv"
SOURCES_OUT = GENERATED / "uk-sources/sources.tsv"
PAGES_OUT = GENERATED / "uk-pages"
# The order the pickers show the nations in — the old roster's, kept in one place.
NATIONS = ["England", "Scotland", "Northern Ireland", "Wales", "Crown Dependencies"]


def mobile_row_kt(p):
    sub = f', "{p["subregion"]}"' if p["subregion"] else ""
    return f'        City("{p["slug"]}", "{p["label"]}", {p["lat"]:.4f}, {p["lon"]:.4f}, "uk", "{p["nation"]}"{sub}),'


def mobile_row_swift(p):
    sub = f', subregion: "{p["subregion"]}"' if p["subregion"] else ""
    return (f'        City(slug: "{p["slug"]}", name: "{p["label"]}", lat: {p["lat"]:.4f}, lon: {p["lon"]:.4f}, '
            f'country: "uk", region: "{p["nation"]}"{sub}),')


MOBILE = [(ROOT / "android/app/src/main/java/pl/kinowo/model/City.kt", mobile_row_kt),
          (ROOT / "ios/Kinowo/Models/City.swift", mobile_row_swift)]
MOBILE_START = "        // ── United Kingdom: GENERATED by data/uk/scripts/generate_roster.py — do not edit by hand.\n"
MOBILE_END = "        // ── end United Kingdom (generated)\n"


def label(p):
    """The name a page shows — the Scala side's `UkPage.labels`, for the apps."""
    return f"{p['name']} area" if p["kind"] == "cluster" else p["name"]


def page_row(p, town_names):
    """A page as `models.UkPages` reads it: slug, name, lat, lon, nation, county, whether it is a
    cluster of towns, its towns' names and its venues' keys."""
    return [p["slug"], p["name"], repr(p["lat"]), repr(p["lon"]), p["nation"], p["county"],
            "true" if p["kind"] == "cluster" else "false",
            list_cell(town_names[t] for t in p["towns"]), list_cell(p["cinemas"])]


def former_names(pages, retired):
    """page slug → the names its retired slugs went by, for the picker's search:
    "West Yorkshire" finds Leeds, "Sandwell" West Bromwich. A name the page already
    answers to — its own, or its county's heading — is left out."""
    by_slug = {p["slug"]: p for p in pages}
    names = collections.defaultdict(list)
    for slug, r in sorted(retired.items()):
        page = by_slug[r["page"]]
        name = r.get("name")
        if name and name.casefold() not in {page["name"].casefold(), page["county"].casefold()}:
            names[r["page"]].append(name)
    return {slug: sorted(set(ns)) for slug, ns in sorted(names.items())}


def pages_tables(pages, retired, town_names):
    """The `models.UkPages` tables, file name → rows: the pages (London first, then pages.json's
    order), the nations in the pickers' order, the retired slugs and the names they went by."""
    unknown = sorted({p["nation"] for p in pages} - set(NATIONS))
    if unknown:
        sys.exit(f"nations with no place in the picker's order: {unknown}")
    london = next(p for p in pages if p["slug"] == "london")
    ordered = [london] + [p for p in pages if p is not london]
    return {
        "pages.tsv": [page_row(p, town_names) for p in ordered],
        "nations.tsv": [[n] for n in NATIONS],
        "retired.tsv": [[k, v["page"]] for k, v in sorted(retired.items())],
        "former-names.tsv": [[k, list_cell(v)] for k, v in former_names(pages, retired).items()],
    }


def venue_rows(groups):
    """The `models.UkRoster` table: each venue's key (roster.json's `object`), display name,
    pill name and opening (`seasonal`, or empty for all year)."""
    return [[v["object"], v["displayName"], v["pillName"], option_cell("seasonal" if v.get("seasonal") else None)]
            for v in uk_roster.venues(groups)]


def source_rows(groups):
    """The `services.cinemas.uk.UkSourcesData` table, in roster.json's (the scrape) order: each
    venue's key, its primary feed's kind and arguments, and the Flicks slug an own-site primary
    falls back to. A Flicks-only venue's primary is `flicks` with its slug."""
    rows = []
    for g in groups:
        for v in g["venues"]:
            if "primary" not in v:
                rows.append([v["object"], "flicks", list_cell([v["flicks"]]), ""])
            else:
                kind, args = v["primary"][0], v["primary"][1:]
                rows.append([v["object"], kind, list_cell(args), option_cell(v.get("flicks") or None)])
    return rows


def write_tables(directory, tables):
    for name, rows in tables.items():
        write_table(directory / name, rows)


def roster_problems(groups, pages):
    """roster.json's own problems, and every venue it and pages.json disagree on: a venue on no
    page is never shown, and a page naming a venue the roster lacks fails `models.UkPages` at startup."""
    found = uk_roster.problems(groups)
    rostered = {v["object"] for v in uk_roster.venues(groups)}
    paged = [c for p in pages for c in p["cinemas"]]
    found += [f"{c}: on a page but not in roster.json" for c in sorted(set(paged) - rostered)]
    found += [f"{c}: in roster.json but on no page" for c in sorted(rostered - set(paged))]
    found += [f"{c}: on more than one page" for c in sorted({c for c in paged if paged.count(c) > 1})]
    return found


def mobile_rows(pages):
    """The apps' fallback rows, in pages.json order (the majors biggest first,
    London leading): a county holding more than one page is the third picker
    step (`subregion`), as `/api/catalog` sends it."""
    per_county = collections.Counter((p["nation"], p["county"]) for p in pages)
    return [dict(p, label=label(p), subregion=p["county"] if per_county[(p["nation"], p["county"])] > 1 else None)
            for p in pages]


def splice(text, rows, line):
    """`text` with the UK block between the markers replaced by `rows`."""
    head, rest = text.split(MOBILE_START, 1)
    _, tail = rest.split(MOBILE_END, 1)
    return head + MOBILE_START + "".join(line(p) + "\n" for p in rows) + MOBILE_END + tail


def main():
    data = json.loads(PAGES.read_text(encoding="utf-8"))
    town_names = {k: t["name"] for k, t in json.loads(TOWNS.read_text(encoding="utf-8"))["towns"].items()}
    pages, retired = data["pages"], data["retired"]
    groups = uk_roster.load()
    found = roster_problems(groups, pages)
    if found:
        sys.exit("data/uk/roster.json cannot be generated from:\n  " + "\n  ".join(found))
    write_table(VENUES_OUT, venue_rows(groups))
    write_table(SOURCES_OUT, source_rows(groups))
    write_tables(PAGES_OUT, pages_tables(pages, retired, town_names))
    rows = mobile_rows(pages)
    for path, line in MOBILE:
        path.write_text(splice(path.read_text(encoding="utf-8"), rows, line), encoding="utf-8")
    print(f"Wrote {VENUES_OUT.relative_to(ROOT)} + {SOURCES_OUT.relative_to(ROOT)}: "
          f"{len(uk_roster.venues(groups))} venues in {len(groups)} groups")
    print(f"Wrote {PAGES_OUT.relative_to(ROOT)}: London and {len(pages) - 1} generated pages, {len(retired)} retired slugs")


if __name__ == "__main__":
    main()
