import threading
import unittest
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import image_pins  # noqa: E402

OLD = "sha256:" + "a" * 64
NEW = "sha256:" + "b" * 64


class Choose(unittest.TestCase):
    def test_semver_within_major_and_later_major(self):
        self.assertEqual(image_pins.choose("v1.0.28", ["v1.0.27", "v1.0.28", "v1.4.22", "v1.4.3", "v2.0.0", "latest",
                                                       "v1.5.0-rc1", "SNAPSHOT-PR-603"], image_pins.SEMVER),
                         ("v1.4.22", "v2.0.0"))

    def test_nothing_newer(self):
        self.assertEqual(image_pins.choose("v0.45.0", ["v0.44.0", "v0.45.0"], image_pins.SEMVER), (None, None))

    def test_jdk_majors(self):
        self.assertEqual(image_pins.choose("27-jdk", ["26-jdk", "27-jdk", "27-jdk-alpine", "28-jdk"], r"(\d+)-jdk"),
                         (None, "28-jdk"))

    def test_ubuntu_lts_only(self):
        self.assertEqual(image_pins.choose("26.04", ["24.04", "26.04", "26.10", "28.04"], r"(\d\d)\.(04)"),
                         (None, "28.04"))

    def test_two_part_tag_reads_as_patch_zero(self):
        self.assertEqual(image_pins.choose("5.10", ["5.10", "5.10.1", "6.4.1"], r"(\d+)\.(\d+)(?:\.(\d+))?"),
                         ("5.10.1", "6.4.1"))

    def test_unreadable_pin_refused(self):
        with self.assertRaises(ValueError):
            image_pins.choose("latest", ["v1.0.0"], image_pins.SEMVER)


class Files(unittest.TestCase):
    buildkit = image_pins.PINS[[p.name for p in image_pins.PINS].index("moby/buildkit")].pattern

    def test_every_form_rewritten(self):
        text = ("driver-opts: image=mirror.gcr.io/moby/buildkit:v0.33.1\n"
                "driver-opts: image=moby/buildkit:v0.33.1\nnot/moby/buildkitx:v0.33.1\n")
        self.assertEqual(image_pins.read_pin(text, self.buildkit), ("v0.33.1", None))
        self.assertEqual(image_pins.rewrite(text, self.buildkit, "v0.34.1"),
                         text.replace("buildkit:v0.33.1", "buildkit:v0.34.1"))

    def test_digest_refreshed_tag_kept(self):
        pattern = image_pins.re.compile(image_pins.image_ref("eclipse-temurin"))
        text = f"FROM mirror.gcr.io/library/eclipse-temurin:27-jdk@{OLD} AS jdk\n"
        self.assertEqual(image_pins.read_pin(text, pattern), ("27-jdk", OLD))
        self.assertEqual(image_pins.rewrite(text, pattern, "27-jdk", NEW), text.replace(OLD, NEW))

    def test_flux_header(self):
        flux = next(p for p in image_pins.PINS if p.name == "flux").pattern
        text = "---\n# This manifest was generated by flux. DO NOT EDIT.\n# Flux Version: v2.9.4\nkind: Namespace\n"
        self.assertEqual(image_pins.read_pin(text, flux), ("v2.9.4", None))

    def test_disagreeing_or_missing_refused(self):
        for text in ("image=moby/buildkit:v0.33.1\nimage=moby/buildkit:v0.32.0\n", "nothing here\n"):
            with self.assertRaises(ValueError):
                image_pins.read_pin(text, self.buildkit)


class FakeRegistry(BaseHTTPRequestHandler):
    tags = {"acme/tool": [["v1.0.0", "v1.1.0"], ["v1.2.0", "v2.0.0"]]}
    digests = {("acme/tool", "v1.0.0"): NEW}

    def log_message(self, *args):
        pass

    def reply(self, code, body=b"", headers=()):
        self.send_response(code)
        for k, v in headers:
            self.send_header(k, v)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def authorised(self):
        if self.headers.get("Authorization") == "Bearer t0ken":
            return True
        realm = f"http://127.0.0.1:{self.server.server_address[1]}/token"
        self.reply(401, headers=[("WWW-Authenticate", f'Bearer realm="{realm}",service="fake",scope="pull"')])
        return False

    def do_GET(self):
        if self.path.startswith("/token?"):
            return self.reply(200, json.dumps({"token": "t0ken"}).encode())
        if not self.authorised():
            return
        page = 1 if "last=" in self.path else 0
        pages = self.tags["acme/tool"]
        headers = [("Link", '</v2/acme/tool/tags/list?last=v1.1.0&n=1000>; rel="next"')] if page + 1 < len(pages) else []
        self.reply(200, json.dumps({"name": "acme/tool", "tags": pages[page]}).encode(), headers)

    def do_HEAD(self):
        if self.authorised():
            self.reply(200, headers=[("Docker-Content-Digest", self.digests[("acme/tool", "v1.0.0")])])


class Protocol(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.server = ThreadingHTTPServer(("127.0.0.1", 0), FakeRegistry)
        threading.Thread(target=cls.server.serve_forever, daemon=True).start()
        cls.base = f"http://127.0.0.1:{cls.server.server_address[1]}"

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()

    def test_token_then_every_page(self):
        self.assertEqual(image_pins.Registry(self.base).tags("acme/tool"), ["v1.0.0", "v1.1.0", "v1.2.0", "v2.0.0"])

    def test_digest(self):
        self.assertEqual(image_pins.Registry(self.base).digest("acme/tool", "v1.0.0"), NEW)

    def check(self, policy, text, root="repo"):
        with tempfile.TemporaryDirectory() as d:
            tree = pathlib.Path(d)
            (tree / "gitops").mkdir()
            target = tree / ("gitops" if root == "gitops" else "") / "Dockerfile"
            target.write_text(text)
            pin = image_pins.Pin("tool", ["Dockerfile"], self.base, "acme/tool", policy, root=root)
            row = image_pins.check(pin, tree, tree / "gitops", apply=True)
            return row, target.read_text()

    def test_minor_bumps_within_major_and_writes(self):
        row, text = self.check("minor", "FROM r.example/acme/tool:v1.0.0\n")
        self.assertEqual((row["action"], row["latest"], row["later"]), ("bumped", "v1.2.0", "v2.0.0"))
        self.assertEqual(text, "FROM r.example/acme/tool:v1.2.0\n")

    def test_digest_policy_refreshes_digest(self):
        row, text = self.check("digest", f"FROM acme/tool:v1.0.0@{OLD}\n")
        self.assertEqual(row["action"], "bumped")
        self.assertEqual(text, f"FROM acme/tool:v1.0.0@{NEW}\n")

    def test_report_policy_never_writes(self):
        row, text = self.check("report", "image: acme/tool:v1.0.0\n")
        self.assertEqual((row["action"], text), ("behind", "image: acme/tool:v1.0.0\n"))

    def test_gitops_pin_never_writes(self):
        row, text = self.check("minor", "image: acme/tool:v1.0.0\n", root="gitops")
        self.assertEqual((row["action"], row["files"], text), ("behind", ["gitops/Dockerfile"], "image: acme/tool:v1.0.0\n"))
        self.assertIn("bump by hand** in movies-gitops", image_pins.markdown([row], []))


class RealPins(unittest.TestCase):
    """The checked-in files keep the shape the weekly run reads."""

    def shapes(self, root):
        for pin in (p for p in image_pins.PINS if p.root == root):
            base = pin.base(image_pins.ROOT, image_pins.GITOPS)
            found = {f: image_pins.read_pin((base / f).read_text(), pin.pattern) for f in pin.files}
            self.assertEqual(len(set(found.values())), 1, f"{pin.name}: the files disagree: {found}")
            tag, digest = next(iter(found.values()))
            self.assertIsNotNone(image_pins.key(tag, pin.tag_key), f"{pin.name}: {tag} does not read as {pin.tag_key}")
            if pin.policy == "digest":
                self.assertIsNotNone(digest, f"{pin.name}: a digest pin with no @sha256")

    def test_this_repository(self):
        self.shapes("repo")

    @unittest.skipUnless((image_pins.GITOPS / ".git").exists(), "no movies-gitops checkout (infra/bin/fetch-gitops)")
    def test_movies_gitops(self):
        self.shapes("gitops")


if __name__ == "__main__":
    unittest.main()
