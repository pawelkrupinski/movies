  private val byName = all.map(c => c.name -> c).toMap

  /** The entry registered under `name`; THROWS for one not registered. */
  def apply(name: String): RegisteredCollection =
    byName.getOrElse(name, throw new NoSuchElementException(s"collection $name is not registered in services.MongoCollections"))

  /** The collections the local prod mirror syncs. */
  def mirrored: Seq[RegisteredCollection] = all.filter(_.mirrored.isDefined)

  /** The collections the nightly recording captures read-only from prod. */
  def recorded: Set[String] = all.filter(_.recorded).map(_.name).toSet

  /** The collections production's identity resolve reads besides what a recording replays. */
  def readByResolve: Set[String] = all.filter(_.readByResolve).map(_.name).toSet

  /** Of [[readByResolve]], those the live drift check resolves over the captures of. */
  def capturedForDrift: Set[String] =
    all.filter(_.resolve.exists { case ResolveRole.Input(_, uncaptured) => uncaptured.isEmpty; case _ => false }).map(_.name).toSet

  /** The collections in `database`. */
  def in(database: CollectionDatabase): Set[String] = all.filter(_.database == database).map(_.name).toSet
