package deploy

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Paths}

import models.Country
import services.FleetDatabase

/** The Mongo roles every database needs, derived from the model, as `scripts/mongo-grants` reads them.
 *
 *  Two principals, named by ROLE and never by user name: `scripts/mongo-grants` reads the user and the database
 *  its record lives in off each one's connection string (the app's `MONGODB_URI`; the CI reader's from the
 *  `mongo-ci-read` endpoint), because the user names are what drifted (`kinowo_app` in every doc while prod ran
 *  `kinowo_app_2`, 2026-10-25).
 *
 *  - `app`: `readWrite` on every country's corpus and on the fleet's own database. Both the setting's fallback
 *    ([[FleetDatabase.Legacy]], Poland's corpus) and [[FleetDatabase.Dedicated]] are covered, so the grant holds
 *    on either side of the move.
 *  - `ci-read`: `read` on every country's corpus (the nightly fixture recorder), and nothing else.
 *
 *  Checked in as `scripts/mongo-grants.tsv` so the tool needs no JVM; [[MongoGrantsListSpec]] fails when the
 *  file and the model disagree. Regenerate: `sbt 'worker/Test/runMain deploy.MongoGrantsList'`. */
object MongoGrantsList {

  val Path = "scripts/mongo-grants.tsv"

  /** (principal, role, database), in the order the file lists them. */
  val grants: Seq[(String, String, String)] = {
    val countries = Country.all.map(_.mongoDb)
    (countries :+ FleetDatabase.Dedicated.value).distinct.map(("app", "readWrite", _)) ++
      countries.map(("ci-read", "read", _))
  }

  val rendered: String =
    s"""# GENERATED by `sbt 'worker/Test/runMain deploy.MongoGrantsList'` from models.Country.all and
       |# services.FleetDatabase; do not edit. Read by scripts/mongo-grants. Columns: principal, role, database.
       |# app = the user in the app's MONGODB_URI; ci-read = the user the mongo-ci-read endpoint hands to CI.
       |${grants.map { case (who, role, db) => s"$who\t$role\t$db" }.mkString("\n")}
       |""".stripMargin

  def main(args: Array[String]): Unit = {
    Files.write(Paths.get(Path), rendered.getBytes(StandardCharsets.UTF_8))
    println(s"wrote $Path (${grants.size} grants)")
  }
}
