package deploy

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Paths}

import models.Country
import services.{CollectionDatabase, FleetDatabase, MongoCollections}

/** The Mongo roles every database needs, derived from the model, as `scripts/mongo-grants` reads them.
 *
 *  Two principals, named by ROLE and never by user name: `scripts/mongo-grants` reads the user and the database
 *  its record lives in off each one's connection string (the app's `MONGODB_URI`; the CI reader's from the
 *  `mongo-ci-read` endpoint), because the user names are what drifted (`kinowo_app` in every doc while prod ran
 *  `kinowo_app_2`, 2026-10-25).
 *
 *  - `app`: `readWrite` on the database of every collection in [[services.MongoCollections]]: every country's corpus and
 *    the fleet's own database ([[FleetDatabase.Dedicated]]).
 *  - `ci-read`: `read` on the databases of the collections the nightly fixture recorder captures (every country's
 *    corpus), and nothing else.
 *
 *  Checked in as `scripts/mongo-grants.tsv` so the tool needs no JVM; [[MongoGrantsListSpec]] fails when the
 *  file and the model disagree. Regenerate: `sbt 'worker/Test/runMain deploy.MongoGrantsList'`. */
object MongoGrantsList {

  val Path = "scripts/mongo-grants.tsv"

  /** The prod databases a registry home stands for: every country's corpus, the fleet's own database. The accounts
   *  database is a corpus one (`MONGODB_USERS_DB`, else the deployment's own), and the review pages' is the local
   *  mirror's, never prod's. */
  private def databasesOf(home: CollectionDatabase): Seq[String] = home match {
    case CollectionDatabase.Corpus      => Country.all.map(_.mongoDb)
    case CollectionDatabase.Fleet       => Seq(FleetDatabase.Dedicated.value)
    case CollectionDatabase.Users       => Nil
    case CollectionDatabase.LocalReview => Nil
  }

  private def databasesHolding(collections: Seq[services.RegisteredCollection]): Seq[String] =
    CollectionDatabase.values.toSeq.filter(home => collections.exists(_.database == home)).flatMap(databasesOf).distinct

  /** (principal, role, database), in the order the file lists them: the app writes every registered collection's
   *  database, the CI reader reads those of the collections the recording captures. */
  val grants: Seq[(String, String, String)] =
    databasesHolding(MongoCollections.all).map(("app", "readWrite", _)) ++
      databasesHolding(MongoCollections.all.filter(_.recorded)).map(("ci-read", "read", _))

  val rendered: String =
    s"""# GENERATED by `sbt 'worker/Test/runMain deploy.MongoGrantsList'` from models.Country.all and
       |# services.FleetDatabase; do not edit. Read by scripts/mongo-grants. Columns: principal, role, database.
       |# app = the user in the app's MONGODB_URI; ci-read = the user the mongo-ci-read endpoint hands to CI.
       |${grants.map { case (who, role, db) => s"$who\t$role\t$db" }.mkString("\n")}
       |""".stripMargin

  def main(args: Array[String]): Unit = {
    Files.write(Paths.get(Path), rendered.getBytes(StandardCharsets.UTF_8))
    println(s"wrote $Path (${grants.size} grants)")
  }
}
