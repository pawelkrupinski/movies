package services.sharecards

import tools.ScratchDirectories
import org.scalatest.flatspec.AnyFlatSpec
import org.scalatest.matchers.should.Matchers

import java.nio.file.Files

/** The case of [[ShareCardPostersSpec]] that runs a real vips child to make a giant progressive poster. */
class ShareCardPostersIntegrationSpec extends AnyFlatSpec with Matchers with ScratchDirectories {

  "The shrinker" should "refuse a real 8000×12000 progressive JPEG before decoding it, with the worker's memory untouched" in {
    val vips = VipsPosterShrinker.locate(settings.ProcessConfiguration.resolve().executableSearchPath)
    assume(vips.isDefined, "vips is not installed")
    val dir  = tempDirectory("giant-poster-")
    val big  = dir.resolve("big.jpg")
    // Generated by vips itself: a 96-megapixel raster built in the JVM would be the very allocation
    // this path exists to avoid.
    def run(args: String*): Unit = new ProcessBuilder((vips.get.value +: args)*).inheritIO().start().waitFor() shouldBe 0
    run("gaussnoise", dir.resolve("n.v").toString, "8000", "12000")
    run("cast", dir.resolve("n.v").toString, dir.resolve("u.v").toString, "uchar")
    run("jpegsave", dir.resolve("u.v").toString, big.toString, "--interlace", "--Q", "80")
    val (refused, allocated) = tools.costs.AllocationMeter.of(new VipsPosterShrinker(binary = vips).coverSlot(big))
    refused shouldBe Left(PosterFailure.ProgressiveEstimate)
    info(tools.costs.PerformanceBudgets.GiantProgressivePosterRefusal.render(allocated))
    tools.costs.PerformanceBudgets.GiantProgressivePosterRefusal.check(allocated)
    Files.list(dir).forEach(Files.delete(_)); Files.delete(dir)
  }
}
