package services.metrics

import io.prometheus.metrics.model.snapshots._

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path}
import scala.jdk.CollectionConverters._

/**
 * THE METRIC CATALOGUE: every application metric family as the code declares it at boot — its name, type, the sample
 * name a query spells, its labels with every value seeded before the first event, and what it reads at boot (`0`,
 * `NaN` for a reading not taken yet, or `none` for a family with no series until a wiring names one) — written to
 * infra/test/app-metrics-catalogue/<tier>.json by the tier's `MetricsAtBootSpec`.
 *
 * WHY ONE. A new metric used to owe three things, each held by a different check that could disagree with the
 * others: a dashboard panel (GrafanaMetricCoverageSpec), a boot-time seed (the AtBoot specs), and a hand exemption in
 * test_label_shapes.py ("NOT PUBLISHED YET") because the fleet snapshot could not have seen a series that had never
 * run — dbd9777dd was that last one turning Stage NixOS closures red. The metric's own registration is the one
 * declaration; this file is it, read by the infra checks: test_label_shapes.py accepts any value the code declares,
 * app_metrics_absent.py takes each family's tier from it, test_alert_rule_coverage.py its NaN-seeded families, and
 * test_dashboards.py requires each family on a panel.
 *
 * `country` is left out: the scrape's target label replaces it.
 */
object MetricCatalogue {

  /** Set to regenerate the catalogue files instead of comparing against them. */
  val WriteVariable = "KINOWO_WRITE_METRIC_CATALOGUE"

  def render(snapshots: MetricSnapshots, tier: String): String = {
    val families = snapshots.asScala.toSeq
      .filter(_.getMetadata.getPrometheusName.startsWith("kinowo_"))
      .sortBy(_.getMetadata.getPrometheusName)
    families.map(family(_, tier)).mkString("{\n  \"comment\": " + quote(Comment) + ",\n  \"families\": [\n", ",\n", "\n  ]\n}\n")
  }

  /** The checked-in file at `path` against `rendered`: `None` when equal (or just written), else why not. */
  def check(path: Path, rendered: String): Option[String] =
    if (sys.env.get(WriteVariable).contains("1")) { Files.writeString(path, rendered, StandardCharsets.UTF_8); None }
    else if (Files.exists(path) && Files.readString(path, StandardCharsets.UTF_8) == rendered) None
    else Some(s"$path is stale: re-run this spec with $WriteVariable=1 and commit it")

  private val Comment =
    "GENERATED by the tier's MetricsAtBootSpec from the registry as it stands at boot (services.metrics.MetricCatalogue) -- do not edit."

  private def family(snapshot: MetricSnapshot, tier: String): String = {
    val points = snapshot.getDataPoints.asScala.toSeq
    val name = snapshot match {
      case _: CounterSnapshot => snapshot.getMetadata.getPrometheusName.stripSuffix("_total")
      case _                  => snapshot.getMetadata.getPrometheusName
    }
    val (kind, sample) = snapshot match {
      case _: CounterSnapshot   => ("counter", name + "_total")
      case _: HistogramSnapshot => ("histogram", name + "_count")
      case _: SummarySnapshot   => ("summary", name + "_count")
      case _: GaugeSnapshot     => ("gauge", name)
      case _                    => ("other", name)
    }
    val labels = points.flatMap(_.getLabels.asScala.map(l => l.getName -> l.getValue)).filterNot(_._1 == "country")
      .groupMap(_._1)(_._2).view.mapValues(_.distinct.sorted).toSeq.sortBy(_._1)
    val values = points.collect {
      case g: GaugeSnapshot.GaugeDataPointSnapshot => g.getValue
      case _                                       => 0.0
    }
    val boot = if (points.isEmpty) "none" else if (values.exists(_.isNaN)) "NaN" else "0"
    val labelJson = labels.map { case (l, vs) => s"${quote(l)}: [${vs.map(quote).mkString(", ")}]" }.mkString("{", ", ", "}")
    s"""    {"name": ${quote(name)}, "tier": ${quote(tier)}, "type": ${quote(kind)}, "sample": ${quote(sample)}, "boot": ${quote(boot)}, "labels": $labelJson}"""
  }

  private def quote(s: String): String =
    "\"" + s.flatMap {
      case '"'            => "\\\""
      case '\\'           => "\\\\"
      case c if c < ' '   => f"\\u${c.toInt}%04x"
      case c              => c.toString
    } + "\""
}
