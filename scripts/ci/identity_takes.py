#!/usr/bin/env python3
"""THE TAKES: the identity tools' files of takes, each read one way, and what a listing's take moving between two of them
is -- shared by the identity takes check (identity_takes_diff.py), scripts/identity-slice's diff (identity_slice_diff.py),
the judgements lint, scripts/label-lookup and scripts/identity-ratchet-report. The judgements themselves are
identity_judgements.py's.

The files, every one tab-separated and led by a header line:
  expected-matches.tsv  test/resources/fixtures/identity-unmatched/: the ratchet's expected right takes
                        (country venue rawTitle film title), regenerated by the ratchet, never edited by hand
  ratchet-takes.tsv     target/identity-unmatched/: UnmatchedClustersRatchetSpec's findings (UnmatchedClusters.FindingsHeader)
  a slice's --out       scripts.IdentitySlice: one decided listing a row (selector key venue rawTitle film ... verdict explanation)

A move, of one listing between two sides (a base and a head, two refs):
  by its film       lost (a film, then none), changed (another film), gained (none, then a film) -- `moved`
  by its verdicts   cured (a WRONG take gone), lost (a RIGHT take gone), new-wrong, won (a RIGHT take new), unjudged --
                    `outcome`, over the verdicts the two sides' takes carry
The takes check reads the first and judges each move by the judgements; the slice diff tallies the second.
"""

from identity_judgements import lines

EXPECTED_MATCHES = "test/resources/fixtures/identity-unmatched/expected-matches.tsv"


class Record(dict):
    """One row of a table: {column: value} -- a row shorter than the header lacks the columns past its end -- and the
    `line` it stands on."""
    __slots__ = ("line",)

    def __init__(self, fields, line):
        super().__init__(fields)
        self.line = line


def table(path):
    """[Record] of a header-led tab-separated file, in file order: blank lines, "#" comments and a repeated header line
    skipped."""
    header, out = None, []
    for n, cols in lines(path):
        if header is None:
            header = cols
        elif cols[0] != header[0]:
            out.append(Record(zip(header, cols), n))
    return out


def expected_matches(path):
    """[(line, country, venue, rawTitle, film, title)]: expected-matches.tsv's expected takes, a row naming no film
    skipped."""
    return [(r.line, r["country"], r["venue"], r["rawTitle"], r["film"], r.get("title", "")) for r in table(path)
            if "film" in r]


# ── a take's move ─────────────────────────────────────────────────────────────────────────

def moved(before, after):
    """What a listing's take moving from film `before` to film `after` (None: no film) is: "lost", "changed" or
    "gained" -- None when it did not move."""
    if before == after:
        return None
    if after is None:
        return "lost"
    if before is None:
        return "gained"
    return "changed"


OUTCOMES = ("cured", "lost", "new-wrong", "won", "moved (unjudged)")


def outcome(was, now):
    """What a move did by its verdicts, `was` the take's before it and `now` after (RIGHT, WRONG, anything else
    unjudged): one of OUTCOMES, a WRONG take gone first."""
    if was == "WRONG" and now != "WRONG":
        return "cured"
    if was == "RIGHT" and now != "RIGHT":
        return "lost"
    if now == "WRONG" and was != "WRONG":
        return "new-wrong"
    if now == "RIGHT" and was != "RIGHT":
        return "won"
    return "moved (unjudged)"
