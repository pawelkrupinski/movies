#!/usr/bin/env python3
"""THE SWIFT AND KOTLIN MEASURES' tests (mobile_quality_measure.py) over an in-memory lizard, and the ratchets' held paths
(mobile_quality_ratchet.py): which code a baseline holds, each function's rows, a file's lines less its
generated roster, the clone groups over lizard's tokens with comments and imports left out."""
from __future__ import annotations

import os
import re
import sys
import unittest
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Sequence

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE]
import mobile_quality_measure as measure  # noqa: E402
import mobile_quality_ratchet as ratchet  # noqa: E402


@dataclass(frozen=True)
class Fn:
    name: str
    cyclomatic_complexity: int
    cognitive_complexity: int
    length: int


@dataclass(frozen=True)
class Info:
    function_list: Sequence[Fn]


@dataclass
class InMemoryLizard:
    """Each file's functions as given; its tokens split as lizard does (words, spaces, newlines, comments)."""
    functions: Dict[str, List[Fn]] = field(default_factory=lambda: {})

    def analyze(self, path: str, code: str) -> measure.FileInfo:
        return Info(self.functions.get(path, []))

    def tokens(self, path: str, code: str) -> Iterable[str]:
        return re.findall(r"//[^\n]*|\n|[ \t]+|\w+|.", code)


def body(n: int) -> str:
    return "".join(f"    let value{i} = compute({i}, other{i})\n" for i in range(n))


class MeasureTest(unittest.TestCase):
    def test_each_function_is_keyed_by_name_a_repeat_numbered(self) -> None:
        lizard = InMemoryLizard({"ios/Kinowo/A.swift": [Fn("body", 12, 11, 60), Fn("body", 1, 0, 3)]})
        rows = measure.rows(lizard, {"ios/Kinowo/A.swift": "x\n"})
        self.assertIn(("cognitive", "ios/Kinowo/A.swift:body", 11), rows)
        self.assertIn(("cyclomatic", "ios/Kinowo/A.swift:body", 12), rows)
        self.assertIn(("method-lines", "ios/Kinowo/A.swift:body", 60), rows)
        self.assertIn(("cyclomatic", "ios/Kinowo/A.swift:body#2", 1), rows)

    def test_a_generated_roster_counts_toward_no_file_length(self) -> None:
        text = ("val a = 1\n// ── Poland: GENERATED by data/pl/scripts/generate_polish_pages.py — do not edit by hand.\n"
                "City(1)\nCity(2)\n// ── end Poland (generated)\nval b = 2\n")
        rows = measure.rows(InMemoryLizard(), {"android/app/src/main/java/C.kt": text})
        self.assertIn(("file-lines", "android/app/src/main/java/C.kt", 2), rows)

    def test_a_copied_block_of_50_tokens_is_a_clone_comments_and_imports_aside(self) -> None:
        a = "import Foundation\n// one\nfunc a() {\n" + body(6) + "}\n"
        b = "import UIKit\n// two, worded otherwise\nfunc a() {\n" + body(6) + "}\n"
        rows = measure.rows(InMemoryLizard(), {"ios/Kinowo/A.swift": a, "ios/Kinowo/B.swift": b})
        self.assertIn(("copies", "ios/Kinowo/A.swift|ios/Kinowo/B.swift", 2), rows)

    def test_a_short_copy_is_no_clone(self) -> None:
        rows = measure.rows(InMemoryLizard(), {"ios/Kinowo/A.swift": body(1), "ios/Kinowo/B.swift": body(1)})
        self.assertFalse([r for r in rows if r[0] == "copies"])

    def test_only_production_code_is_held(self) -> None:
        swift, kotlin = (ratchet.SPECS[n].held for n in ("swift", "kotlin"))
        self.assertTrue(swift("ios/Kinowo/Views/CityGate.swift:body"))
        self.assertFalse(swift("ios/Tests/KinowoCoreTests/X.swift:test"))
        self.assertFalse(swift("ios/KinowoUITests/X.swift:test"))
        self.assertTrue(kotlin("android/app/src/main/java/pl/kinowo/A.kt:f"))
        self.assertTrue(kotlin("android/app/src/tuning/java/pl/kinowo/A.kt"))
        self.assertFalse(kotlin("android/app/src/test/java/pl/kinowo/ATest.kt:f"))
        self.assertTrue(kotlin("android/app/build.gradle.kts"))  # the Gradle scripts are held (2026-11-28)

    def test_each_language_holds_its_own_files(self) -> None:
        self.assertTrue(measure.LANGUAGES["swift"].holds("ios/Kinowo/A.swift"))
        self.assertFalse(measure.LANGUAGES["swift"].holds("android/app/src/main/java/A.kt"))
        self.assertTrue(measure.LANGUAGES["kotlin"].holds("android/app/src/main/java/A.kt"))


if __name__ == "__main__":
    unittest.main()
