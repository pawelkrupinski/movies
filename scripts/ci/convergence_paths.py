#!/usr/bin/env python3
"""THE CONVERGENCE PATHS' CI PART, GENERATED: every repository file the convergence workflows run.

.github/convergence-paths.txt says which paths can change a convergence leg's verdict (kick-convergence.sh dispatches
only for them, convergence-bisect.sh bisects only over them, convergence_reuse.py keys a reuse by them). Its hand-written
part lists the sources, the data the legs read and the directories of whole actions. Its GENERATED block lists every
other repository file the convergence workflows run -- each `uses: ./...` and every `.github/...` or `scripts/...` path
they name, transitively -- so a new helper a leg runs is listed the moment it is referenced, not after a red Main
(#2877, run 4452: one omission; the list was edited in 8 commits in a week by hand).

    scripts/ci/convergence_paths.py --write    rewrite the block (scripts/hooks/pre-commit runs it)
    scripts/ci/convergence_paths.py --check    exit 1, naming the difference, when the block is stale
                                               (ConvergenceDispatchGateSpec runs it on CI)
Tested by convergence_paths_test.py.
"""
import os
import re
import sys

PATHS = ".github/convergence-paths.txt"
ROOTS = (".github/workflows/identity-model-convergence.yml", ".github/workflows/country-convergence-leg.yml")
# What the workflows run only after the verdict is in: never part of it.
AFTER_THE_VERDICT = {
    ".github/actions/convergence-bisect-request/action.yml",  # asks for a bisect of a red run
    ".github/actions/hard-clusters-ratchet/action.yml",      # turns a red leg's findings into seeds
    ".github/actions/report-timings/action.yml",             # reports the run's step timings
    ".github/workflows/report-timings.yml",                  # ...dispatched by its last job, `timings`
    "scripts/ci/ci_http_calls.py",                           # reports the external services a job called
}
# Read as data, not run: what it names is this generator's business, not the workflows'.
READ_AS_DATA = {PATHS}
BEGIN = "# BEGIN GENERATED by scripts/ci/convergence_paths.py --write: every other repository file the convergence"
BEGIN_2 = "# workflows run (`uses: ./...` and every .github/ or scripts/ path they name, transitively). Do not edit."
END = "# END GENERATED"
REFERENCE = re.compile(r"(?:\./)?((?:\.github|scripts)/[\w./-]*\w)")


def referenced_by(root, path):
    try:
        with open(os.path.join(root, path), encoding="utf-8") as f:
            lines = [l for l in f.read().splitlines() if not l.strip().startswith("#")]
    except OSError:
        return set()
    found = set()
    for line in lines:
        for ref in REFERENCE.findall(line):
            if os.path.isfile(os.path.join(root, ref)):
                found.add(ref)
            elif os.path.isfile(os.path.join(root, ref, "action.yml")):
                found.add(f"{ref}/action.yml")
    return found


def run_by_workflows(root):
    seen, frontier = set(ROOTS), set(ROOTS)
    while frontier:
        nxt = set()
        for f in frontier - AFTER_THE_VERDICT - READ_AS_DATA:
            nxt |= referenced_by(root, f)
        frontier = nxt - seen
        seen |= frontier
    return seen - AFTER_THE_VERDICT


def split(text):
    """(hand-written lines, generated lines) of the paths file."""
    lines = text.splitlines()
    if BEGIN not in lines:
        return lines, []
    b = lines.index(BEGIN)
    e = lines.index(END, b)
    return lines[:b] + lines[e + 1:], [l for l in lines[b + 1:e] if l and not l.startswith("#")]


def covered(path, entries):
    return any(path.startswith(p[:-2]) if p.endswith("/**") else path == p for p in entries)


def generated(root, hand):
    entries = [l.strip() for l in hand if l.strip() and not l.strip().startswith("#")]
    return sorted(p for p in run_by_workflows(root) if not covered(p, entries))


def render(hand, block):
    body = "\n".join(hand).rstrip("\n")
    return f"{body}\n{BEGIN}\n{BEGIN_2}\n" + "".join(f"{p}\n" for p in block) + f"{END}\n"


def main(argv):
    root = "."
    if "--root" in argv:
        root = argv[argv.index("--root") + 1]
    path = os.path.join(root, PATHS)
    with open(path, encoding="utf-8") as f:
        text = f.read()
    hand, current = split(text)
    want = generated(root, hand)
    if "--write" in argv:
        new = render(hand, want)
        if new != text:
            with open(path, "w", encoding="utf-8") as f:
                f.write(new)
            print(f"{PATHS}: generated block rewritten ({len(want)} path(s))")
        return 0
    if "--check" in argv:
        missing, extra = sorted(set(want) - set(current)), sorted(set(current) - set(want))
        if missing or extra or render(hand, want) != text:
            for p in missing:
                print(f"{PATHS}: the convergence workflows run {p}, which is not listed", file=sys.stderr)
            for p in extra:
                print(f"{PATHS}: {p} is listed but no convergence workflow runs it", file=sys.stderr)
            print(f"run: python3 scripts/ci/convergence_paths.py --write", file=sys.stderr)
            return 1
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
