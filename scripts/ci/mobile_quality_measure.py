"""THE SWIFT AND KOTLIN MEASURES (scripts/mobile-quality-report, mobile_quality_report.py): every function's cognitive (SonarSource's) and
cyclomatic complexity and its lines, every file's lines -- read by lizard (pinned: requirements.txt), handed in as a
`Lizard` -- and the clone groups of 50+ tokens, every measure's own (scripts/lib/code_tools/clone_groups.py) over lizard's
tokens: whitespace, comments and `import` / `package` lines left out, names kept as written."""
from __future__ import annotations

import os
import re
import sys
from dataclasses import dataclass
from typing import Dict, Iterable, List, Protocol, Sequence, Set, Tuple

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lib"))
from code_tools import clone_groups, quality_report  # noqa: E402

Row = Tuple[str, str, float]
SKIPPED_LINES = ("import", "package")
# a generated roster block inside a hand-written source (City.kt / City.swift: data/<cc>/scripts/generate_*.py writes
# it, the drift check holds it): DATA, as the Scala ratchet's declared tables -- its lines count toward no file's
# length and its tokens toward no clone
GENERATED_START = re.compile(r"GENERATED by .*do not edit")
GENERATED_END = re.compile(r"\(generated\)\s*$")


class Function(Protocol):
    name: str
    cyclomatic_complexity: int
    cognitive_complexity: int
    length: int


class FileInfo(Protocol):
    function_list: Sequence[Function]


class Analyzer(Protocol):
    def analyze_source_code(self, filename: str, code: str) -> FileInfo: ...


class Lizard(Protocol):
    """What the measure reads of lizard: one file's functions, and one language's tokens."""

    def analyze(self, path: str, code: str) -> FileInfo: ...

    def tokens(self, path: str, code: str) -> Iterable[str]: ...


@dataclass(frozen=True)
class Language:
    name: str
    root: str
    suffixes: Tuple[str, ...]

    def holds(self, path: str) -> bool:
        return path.startswith(self.root) and path.endswith(self.suffixes)


LANGUAGES = {"swift": Language("swift", "ios/", (".swift",)), "kotlin": Language("kotlin", "android/", (".kt", ".kts"))}


def generated_lines(text: str) -> Set[int]:
    """The lines of the text's generated blocks, their marker lines included."""
    out: Set[int] = set()
    inside = False
    for number, line in enumerate(text.splitlines(), 1):
        inside = inside or bool(GENERATED_START.search(line))
        if inside:
            out.add(number)
        inside = inside and not GENERATED_END.search(line)
    return out


def function_rows(path: str, info: FileInfo) -> List[Row]:
    """Each function's rows under `<path>:<name>`, a repeated name `#2`, `#3`... in the file's order."""
    rows: List[Row] = []
    found = info.function_list
    for fn, key in zip(found, quality_report.numbered_keys(path, (fn.name for fn in found))):
        rows += [("cognitive", key, fn.cognitive_complexity), ("cyclomatic", key, fn.cyclomatic_complexity),
                 ("method-lines", key, fn.length)]
    return rows


def skipped(token: str) -> bool:
    return token.isspace() or token.startswith(("//", "/*", "#!"))


def tokens_of(raw: Iterable[str], generated: Set[int]) -> List[clone_groups.Token]:
    """The tokens with their lines, bar layout, comments, the `import` / `package` lines and the generated lines."""
    out: List[clone_groups.Token] = []
    line, dropped = 1, -1
    for token in raw:
        if token in SKIPPED_LINES and (not out or out[-1][1] < line):
            dropped = line
        if not skipped(token) and line != dropped and line not in generated:
            out.append((token, line))
        line += token.count("\n")
    return out


def rows(lizard: Lizard, sources: Dict[str, str]) -> List[Row]:
    """Every row of one language's sources (path -> text): functions, files, clone sets."""
    out: List[Row] = []
    for path, text in sorted(sources.items()):
        out += function_rows(path, lizard.analyze(path, text))
        out.append(("file-lines", path, len(text.splitlines()) - len(generated_lines(text))))
    return out + clone_groups.copies_rows({path: tokens_of(lizard.tokens(path, text), generated_lines(text))
                              for path, text in sources.items()})
